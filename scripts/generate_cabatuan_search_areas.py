"""Generate offline search bounds; never infer coordinates from barangay order.

Usage: python scripts/generate_cabatuan_search_areas.py <cabatuan.geojson>
Source: PSA/NAMRIA-derived 2023-10-24 snapshot, NAMRIA validOn 2023-11-06.
"""
import hashlib
import json
from pathlib import Path
import re
import sys
import urllib.request

root = Path(__file__).resolve().parents[1]
raw = Path(sys.argv[1]).read_bytes()
features = json.loads(raw)['features']
names = re.findall(r"^    '([^']+)',", (root / 'lib/utils/location_constants.dart').read_text(), re.M)
names = [name for name in names if name != 'Cabatuan']
normalize = lambda name: re.sub('[^a-z0-9]', '', name.lower())
by_name = {normalize(f['properties']['ADM4_EN']): f for f in features}
assert len(features) == len(names) == 68
assert set(by_name) == {normalize(name) for name in names}

def points(value):
    if isinstance(value, list) and len(value) >= 2 and isinstance(value[0], (float, int)):
        yield value[:2]
    elif isinstance(value, list):
        for child in value:
            yield from points(child)

rows = []
for name in names:
    f = by_name[normalize(name)]
    props = f['properties']
    assert props['ADM3_EN'] == 'Cabatuan' and props['ADM2_EN'] == 'Iloilo'
    coords = list(points(f['geometry']['coordinates']))
    west, east = min(p[0] for p in coords), max(p[0] for p in coords)
    south, north = min(p[1] for p in coords), max(p[1] for p in coords)
    assert 10.7 < south < north < 11.1 and 122.2 < west < east < 122.7
    rows.append((name, south, west, north, east, props['psgc_code']))

header = '''// Generated by scripts/generate_cabatuan_search_areas.py. Do not hand-edit.
// Source: bendlikeabamboo/barangay-boundaries-repository, 2023-10-24 snapshot.
// Underlying boundaries: NAMRIA (validOn 2023-11-06); names/codes: PSA PSGC.
// Indicative, simplified administrative areas for map navigation, not farm plots.
// Upstream attribution and MIT license: docs/cabatuan-search-data.md.
import 'package:flutter_map/flutter_map.dart';
import 'package:latlong2/latlong.dart';

class BarangayMapArea {
  final double south, west, north, east;
  final String psgc;
  const BarangayMapArea(this.south, this.west, this.north, this.east, this.psgc);
  LatLng get center => LatLng((south + north) / 2, (west + east) / 2);
  LatLngBounds get bounds => LatLngBounds(LatLng(south, west), LatLng(north, east));
}

const cabatuanBarangayAreas = <String, BarangayMapArea>{
'''
body = ''.join(f"  '{name}': BarangayMapArea({s:.6f}, {w:.6f}, {n:.6f}, {e:.6f}, '{code}'),\n" for name,s,w,n,e,code in rows)
s, w = min(r[1] for r in rows), min(r[2] for r in rows)
n, e = max(r[3] for r in rows), max(r[4] for r in rows)
output = root / 'lib/data/cabatuan_barangay_areas.dart'
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text(header + body + f"}};\n\nconst cabatuanMunicipalityArea = BarangayMapArea({s:.6f}, {w:.6f}, {n:.6f}, {e:.6f}, '0603012000');\n", encoding='utf-8')
license_text = urllib.request.urlopen('https://raw.githubusercontent.com/bendlikeabamboo/barangay-boundaries-repository/main/LICENSE', timeout=20).read().decode()
doc = root / 'docs/cabatuan-search-data.md'
doc.parent.mkdir(parents=True, exist_ok=True)
doc.write_text(f'''# Cabatuan barangay search data

The offline navigation bounds cover all 68 names in `LocationConstants.cabatuanBarangays`, shared with `veri_form.dart`.
Bounds are calculated from the published polygons, not guessed coordinates. They guide map zoom; users still draw their own farm boundary.

Source: https://github.com/bendlikeabamboo/barangay-boundaries-repository/blob/main/2023-10-24/hierarchical_t0p005/barangays.geojson

Attribution: Philippine Statistics Authority (PSGC names/codes); NAMRIA administrative boundaries, validOn 2023-11-06; enrichment by bendlikeabamboo.
Snapshot: 2023-10-24. Upstream geometries are simplified at 0.005 degrees.
Downloaded Cabatuan subset SHA-256: `{hashlib.sha256(raw).hexdigest()}`.

Name matching removes punctuation/case only: Duyanduyan → Duyan-Duyan, Pamul-Ogan → Pamul-ogan, and spacing in Zone VI are normalized to the app's registration labels.

To regenerate, download the source, filter municipality `ADM3_PCODE = PH0603012`, then run:

`python scripts/generate_cabatuan_search_areas.py <cabatuan.geojson>`

## Upstream license

{license_text}
''', encoding='utf-8')
print('Generated all 68 registration barangays with verified polygon bounds.')
